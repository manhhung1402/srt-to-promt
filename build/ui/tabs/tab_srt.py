import tkinter as tk
from tkinter import ttk
from config.settings import LLM_URLS
from core.whisper_runtime import WHISPER_MODELS
from ui import theme


def create_tab_srt(app, parent):
    tab = ttk.Frame(parent, style='Body.TFrame')

    def label(master, text, style='Card.TLabel'):
        return ttk.Label(master, text=text, style=style)

    inputs = ttk.Frame(tab, style='Card.TFrame', padding=(theme.SP_LG, theme.SP_MD))
    inputs.pack(fill='x')
    ttk.Label(inputs, text='INPUT', style='HeaderHint.TLabel').grid(row=0, column=0, columnspan=4, sticky='w')
    label(inputs, 'Audio / Video').grid(row=1, column=0, sticky='w', pady=(theme.SP_MD, 0))
    app.entry_audio_path = ttk.Entry(inputs)
    app.entry_audio_path.grid(row=1, column=1, columnspan=2, sticky='ew', padx=(theme.SP_MD, theme.SP_SM), pady=(theme.SP_MD, 0))
    ttk.Button(inputs, text='Chọn', style='Ghost.TButton', command=app.browse_audio).grid(row=1, column=3, sticky='e', pady=(theme.SP_MD, 0))
    label(inputs, 'SRT có sẵn').grid(row=2, column=0, sticky='w', pady=(theme.SP_SM, 0))
    app.entry_srt_in_path = ttk.Entry(inputs)
    app.entry_srt_in_path.grid(row=2, column=1, columnspan=2, sticky='ew', padx=(theme.SP_MD, theme.SP_SM), pady=(theme.SP_SM, 0))
    ttk.Button(inputs, text='Chọn', style='Ghost.TButton', command=app.browse_srt_in).grid(row=2, column=3, sticky='e', pady=(theme.SP_SM, 0))
    label(inputs, 'Kịch bản gốc').grid(row=3, column=0, sticky='nw', pady=(theme.SP_SM, 0))
    app.txt_reference_text = theme.style_text(tk.Text(inputs, wrap=tk.WORD), mono=False, height=3)
    app.txt_reference_text.grid(row=3, column=1, columnspan=3, sticky='ew', padx=(theme.SP_MD, 0), pady=(theme.SP_SM, 0))
    whisper_row = ttk.Frame(inputs, style='Card.TFrame')
    whisper_row.grid(row=4, column=0, columnspan=4, sticky='ew', pady=(theme.SP_MD, 0))
    label(whisper_row, 'Whisper', 'Section.TLabel').pack(side='left')
    app.combo_whisper_model = ttk.Combobox(whisper_row, state='readonly', width=24)
    app.combo_whisper_model['values'] = list(WHISPER_MODELS.keys())
    app.combo_whisper_model.current(1)
    app.combo_whisper_model.pack(side='left', padx=(theme.SP_MD, theme.SP_SM))
    app.btn_whisper_download = ttk.Button(whisper_row, text='Cài', style='Ghost.TButton', command=app.start_whisper_install)
    app.btn_whisper_download.pack(side='left')
    app.lbl_whisper_status = ttk.Label(whisper_row, text='', style='Card.Muted.TLabel')
    app.lbl_whisper_status.pack(side='left', padx=theme.SP_MD)
    inputs.columnconfigure(1, weight=2)
    inputs.columnconfigure(2, weight=1)

    # Bang "Cai dat auto" nam ngay ben duoi phan input (3.1)
    from ui.auto_panel import create_auto_panel
    create_auto_panel(app, tab)

    paned = ttk.PanedWindow(tab, orient=tk.HORIZONTAL)
    paned.pack(fill='both', expand=True, pady=(theme.SP_LG, 0))

    left = ttk.Frame(paned, style='Card.TFrame', padding=(theme.SP_LG, theme.SP_MD))
    paned.add(left, weight=1)
    ttk.Label(left, text='BƯỚC 1 · SRT THEO CÂU', style='HeaderHint.TLabel').pack(anchor='w')
    app.btn_gen_srt_sentence = ttk.Button(left, text='Đối chiếu & tạo SRT', style='Primary.TButton',
                                           command=app.start_srt_sentence_thread)
    app.btn_gen_srt_sentence.pack(fill='x', pady=(theme.SP_SM, theme.SP_XS))
    app.lbl_status_left = ttk.Label(left, text='Trạng thái: Chưa chạy', style='Card.Muted.TLabel')
    app.lbl_status_left.pack(anchor='w')
    output_left = ttk.Frame(left, style='Card.TFrame')
    output_left.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(output_left, text='Kết quả', style='Card.Section.TLabel').pack(side='left')
    ttk.Button(output_left, text='Xuất', style='Ghost.TButton', command=app.export_srt_sentence).pack(side='right')
    app.txt_srt_sentence = theme.style_text(tk.Text(left, wrap=tk.NONE))
    app.txt_srt_sentence.pack(fill='both', expand=True, pady=(theme.SP_SM, 0))
    theme.make_scrollable(app.txt_srt_sentence, horizontal=True)
    theme.mark_numbered(app.txt_srt_sentence)

    right = ttk.Frame(paned, style='Card.TFrame', padding=(theme.SP_LG, theme.SP_MD))
    paned.add(right, weight=1)
    ttk.Label(right, text='BƯỚC 2 · GỘP THEO PHÂN CẢNH', style='HeaderHint.TLabel').pack(anchor='w')
    method = ttk.Frame(right, style='Card.TFrame')
    method.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(method, text='Phương thức', style='Section.TLabel').pack(side='left')
    app.scene_method = tk.StringVar(value='llm')
    ttk.Radiobutton(method, text='Thuật toán', value='algo', variable=app.scene_method).pack(side='left', padx=(theme.SP_MD, theme.SP_SM))
    ttk.Radiobutton(method, text='AI', value='llm', variable=app.scene_method).pack(side='left')
    ttk.Label(method, text='LLM (Bước 2)', style='Section.TLabel').pack(side='left', padx=(theme.SP_LG, theme.SP_MD))
    app.combo_llm_step2 = ttk.Combobox(method, textvariable=app.llm_var, values=list(LLM_URLS.keys()), state='readonly')
    app.combo_llm_step2.pack(side='left')

    source = ttk.Frame(right, style='Card.TFrame')
    source.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(source, text='Nguồn (Bước 2)', style='Section.TLabel').pack(side='left')
    ttk.Radiobutton(source, text='API', value='api', variable=app.ai_source_var).pack(side='left', padx=(theme.SP_MD, theme.SP_SM))
    ttk.Radiobutton(source, text='Web', value='web', variable=app.ai_source_var).pack(side='left')
    ttk.Button(source, text='Chrome Chat', style='Ghost.TButton', command=app.manual_open_login).pack(side='left', padx=theme.SP_LG)
    retry_row = ttk.Frame(right, style='Card.TFrame')
    retry_row.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(retry_row, text='Thử lại', style='Section.TLabel').pack(side='left')
    app.combo_api_retry = ttk.Combobox(retry_row, textvariable=app.api_retry_var,
                                       state='readonly', width=10)
    app.combo_api_retry['values'] = app.RETRY_CHOICES
    app.combo_api_retry.pack(side='left', padx=(theme.SP_MD, theme.SP_SM))
    ttk.Label(retry_row, text="'inf' = vô hạn (áp dụng cho API và LLM Web)", style='Card.Muted.TLabel').pack(side='left')

    input_mode = ttk.Frame(right, style='Card.TFrame')
    input_mode.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(input_mode, text='Cách gửi', style='Section.TLabel').pack(side='left')
    app.scene_input_mode = tk.StringVar(value='auto')
    ttk.Radiobutton(input_mode, text='Tự động', value='auto', variable=app.scene_input_mode).pack(side='left', padx=(theme.SP_MD, theme.SP_SM))
    ttk.Radiobutton(input_mode, text='Nhập', value='text', variable=app.scene_input_mode).pack(side='left')
    ttk.Radiobutton(input_mode, text='File', value='file', variable=app.scene_input_mode).pack(side='left')

    duration = ttk.Frame(right, style='Card.TFrame')
    duration.pack(fill='x', pady=(theme.SP_SM, theme.SP_LG))
    ttk.Label(duration, text='Min giây', style='Section.TLabel').pack(side='left')
    app.entry_min_duration = ttk.Entry(duration, width=7)
    app.entry_min_duration.pack(side='left', padx=(theme.SP_MD, theme.SP_LG))
    ttk.Label(duration, text='Max giây', style='Section.TLabel').pack(side='left')
    app.entry_max_duration = ttk.Entry(duration, width=7)
    app.entry_max_duration.insert(0, '60')
    app.entry_max_duration.pack(side='left')
    buttons = ttk.Frame(right, style='Card.TFrame')
    buttons.pack(fill='x')
    app.btn_group_scenes = ttk.Button(buttons, text='Gộp SRT', style='Primary.TButton', command=app.start_group_scenes_thread)
    app.btn_group_scenes.pack(side='left', fill='x', expand=True)
    app.btn_pause_scene = ttk.Button(buttons, text='Tạm dừng', command=app.toggle_pause_scene, state='disabled')
    app.btn_pause_scene.pack(side='left', padx=6)
    ttk.Button(buttons, text='Dừng', style='Danger.TButton', command=lambda: app.manual_reset_chrome(scope='scene')).pack(side='left')
    app.lbl_status_right = ttk.Label(right, text='Trạng thái: Chờ Bước 1', style='Card.Muted.TLabel')
    app.lbl_status_right.pack(anchor='w')
    output_right = ttk.Frame(right, style='Card.TFrame')
    output_right.pack(fill='x', pady=(theme.SP_SM, 0))
    ttk.Label(output_right, text='Kết quả', style='Card.Section.TLabel').pack(side='left')
    ttk.Button(output_right, text='Xuất', style='Ghost.TButton', command=app.export_srt_scene).pack(side='right')
    app.txt_srt_scene = theme.style_text(tk.Text(right, wrap=tk.NONE))
    app.txt_srt_scene.pack(fill='both', expand=True, pady=(theme.SP_SM, 0))
    theme.make_scrollable(app.txt_srt_scene, horizontal=True)
    theme.mark_numbered(app.txt_srt_scene)
    return tab
